// Warp's settings and keybindings for the panel live in settings.toml and keybindings.yaml in the
// extension's storage folder, in the same shape as desktop Warp's ~/.warp files. Web Warp reads and
// writes them as localStorage entries, so the page gets them from the files at startup and every
// change it makes is written back. globalState keeps a mirror of the entries, shared by every
// window: it holds the entries that aren't settings and starts the files on a machine without them.

const vscode = require('vscode');
const fs = require('fs');
const path = require('path');
const { isDeepStrictEqual } = require('util');
const TOML = require('smol-toml');

const { DEFAULTS, decode, encode, confirmPublicRouting } = require('./panelSettings');

// storage key -> TOML path, generated by scripts/gen-settings-map.py from Warp's source.
const SETTINGS_MAP = require('./media/settings-map.json');

// localStorage key our Warp build keeps keybindings.yaml's text under (app/src/keyboard.rs), as a
// JSON string
const KEYBINDINGS_KEY = 'CustomKeybindings';

const KEYBINDINGS_HEADER = `# Warp panel keybindings (same format as desktop Warp's ~/.warp/keybindings.yaml).
# Each line maps an action to its keys, or to none to unbind it, e.g.
# "editor_view:insert_autosuggestion": tab
# "workspace:toggle_command_palette": none
# Saved edits apply to the running panel (Warp builds without live reload offer to reload it).
# Warp rewrites this file without comments when you change a keybinding in its settings.
`;

function getPath(obj, dotted) {
  return dotted.split('.').reduce((node, key) => (node == null ? undefined : node[key]), obj);
}

function setPath(obj, dotted, value) {
  const keys = dotted.split('.');
  const last = keys.pop();
  let node = obj;
  for (const key of keys) node = node[key] ??= {};
  node[last] = value;
}

function deletePath(obj, dotted) {
  const keys = dotted.split('.');
  const last = keys.pop();
  const parents = [];
  let node = obj;
  for (const key of keys) {
    if (node[key] == null || typeof node[key] !== 'object') return;
    parents.push([node, key]);
    node = node[key];
  }
  delete node[last];
  // Drop the tables the delete left empty
  for (const [parent, key] of parents.reverse()) {
    if (Object.keys(parent[key]).length) break;
    delete parent[key];
  }
}

// The panel's settings with their defaults go in the header as comments, so a default that changes
// in a later version still reaches everyone who didn't set it
const panelDefaults = {};
for (const [storageKey, value] of Object.entries(DEFAULTS)) setPath(panelDefaults, SETTINGS_MAP[storageKey], value);

const HEADER = `# Warp panel settings (same format as desktop Warp's ~/.warp/settings.toml).
# Warp reads this file when the panel starts and writes your changes from its settings page here.
# Saved edits apply to the running panel (Warp builds without live reload offer to reload it).
# Only settings you've changed are listed. Removing a setting resets it to its default. Comments
# other than this header are dropped when Warp writes a change.
#
# This file stays on this machine: VS Code Settings Sync only carries command history, and only with
# host.history_sync = true, which syncs your newest 500 commands to your other machines (commands
# starting with a space are left out).
# [host.ai]: models are OpenRouter model ids; expanded_model = "" means fast suggestions only;
# expanded_effort is minimal, low, medium or high; recent_commands_in_context only applies while
# private_routing is on. After a failed command the fast model suggests a fix; next_command = true
# also suggests the next command after successful ones. Both, and prompt_suggestions, send command
# output, so they only run with private_routing on; local_model (e.g. an LM Studio model id) sends all of them to
# local_server instead of OpenRouter; prompt_suggestions_agent is the command an accepted suggestion starts
# (the prompt is added as its last argument). [host.keys_to_host] adds keys that go to VS Code
# instead of Warp, e.g. "cmd+k" = "workbench.action.quickOpen" (an empty command removes a
# built-in one).
#
# The panel's own settings and their defaults. To change one, copy it and its [table] line out of
# this comment.
${TOML.stringify(panelDefaults)
  .trim()
  .split('\n')
  .map((line) => `# ${line}`.trimEnd())
  .join('\n')}
`;

/** Renders the mirrored localStorage entries as settings.toml text. */
function renderToml(entries) {
  const doc = {};
  for (const [storageKey, tomlPath] of Object.entries(SETTINGS_MAP)) {
    if (!(storageKey in entries)) continue;
    // Saving the file in earlier versions stored every panel default, which would keep them from
    // changing in a later version
    if (storageKey in DEFAULTS && holds(entries[storageKey], DEFAULTS[storageKey])) continue;
    try {
      const value = decode(entries[storageKey]);
      if (value !== null) setPath(doc, tomlPath, value);
    } catch {
      // Not a setting value we can represent; leave it out of the file.
    }
  }
  return HEADER + '\n' + TOML.stringify(doc);
}

/** Whether a localStorage entry holds this value. smol-toml's tables have no prototype, so both compare as JSON. */
function holds(raw, value) {
  try {
    return isDeepStrictEqual(decode(raw), JSON.parse(JSON.stringify(value)));
  } catch {
    return false;
  }
}

/** Applies parsed settings.toml text to the mirrored entries; returns the new entries. */
function applyToml(text, entries) {
  const doc = TOML.parse(text);
  const next = { ...entries };
  for (const [storageKey, tomlPath] of Object.entries(SETTINGS_MAP)) {
    const value = getPath(doc, tomlPath);
    if (value === undefined) delete next[storageKey];
    // Keeps Warp's own text for a value the file has unchanged (Warp writes the font size as 13.0,
    // TOML reads it back as 13), so the page isn't sent values it already has
    else if (!holds(next[storageKey], value)) next[storageKey] = encode(value);
  }
  return next;
}

/**
 * Writes changed localStorage entries (null for removed) into settings.toml text; returns the new
 * text. Keys the settings map doesn't know, like ones copied from desktop Warp, stay in the file.
 */
function updateToml(text, changes) {
  const doc = TOML.parse(text);
  for (const [storageKey, raw] of Object.entries(changes)) {
    const tomlPath = SETTINGS_MAP[storageKey];
    if (!tomlPath) continue;
    let value;
    try {
      value = raw === null ? null : decode(raw);
    } catch {
      continue;
    }
    if (value === null) deletePath(doc, tomlPath);
    else setPath(doc, tomlPath, value);
  }
  return HEADER + '\n' + TOML.stringify(doc);
}

/** Puts keybindings.yaml text into the entries; a file without bindings means no custom keybindings. */
function withKeybindings(entries, text) {
  const next = { ...entries };
  // Warp can't parse a file with only comments
  if (text.replace(/^\s*(#.*|---\s*)$/gm, '').trim()) next[KEYBINDINGS_KEY] = JSON.stringify(text);
  else delete next[KEYBINDINGS_KEY];
  return next;
}

/** A file's text; empty when it doesn't exist, which means every setting or keybinding is default. */
function read(file) {
  try {
    return fs.readFileSync(file, 'utf8');
  } catch (error) {
    if (error.code === 'ENOENT') return '';
    throw error;
  }
}

const isPrivateRouting = (entries) =>
  entries.HostAiPrivateRouting === undefined || decode(entries.HostAiPrivateRouting) !== false;

/** Entries that differ between two sets, as changes (null for removed). */
function changedEntries(previous, next) {
  const changes = {};
  for (const key of new Set([...Object.keys(previous), ...Object.keys(next)])) {
    if (!(key in next)) changes[key] = null;
    else if (previous[key] !== next[key]) changes[key] = next[key];
  }
  return changes;
}

class SettingsFile {
  /**
   * @param {vscode.ExtensionContext} context
   * @param {{storageKey: string, onChanged: (changes: object) => boolean,
   *   onApplied: () => Promise<void>, log: vscode.OutputChannel}} options `onChanged` hands a
   *   running Warp the changed entries, and returns false if it can't apply them without a reload
   */
  constructor(context, { storageKey, onChanged, onApplied, log }) {
    this.globalState = context.globalState;
    this.storageKey = storageKey;
    this.onChanged = onChanged;
    this.onApplied = onApplied;
    this.log = log;
    // This window's entries, the ones its page has: the mirror's, with the settings and keybindings
    // from the files once they're loaded. Each window compares the files against its own entries,
    // since the mirror is shared with windows on other machines (remote windows) and changes
    // between them in any order.
    this.state = this.globalState.get(storageKey, {});
    this.pendingChanges = new Set();
    // Set while the files turn private routing off and nothing has asked about it yet
    this.routingPending = false;
    const dir = context.globalStorageUri.fsPath;
    this.file = path.join(dir, 'settings.toml');
    this.keybindingsFile = path.join(dir, 'keybindings.yaml');
    // Markers kept next to the files, so they're per machine like the files
    this.migratedFile = path.join(dir, '.settings-migrated');
    this.routingAllowedFile = path.join(dir, '.private-routing-off-allowed');
    context.subscriptions.push(
      vscode.workspace.onDidSaveTextDocument((doc) => {
        if (doc.uri.fsPath === this.file || doc.uri.fsPath === this.keybindingsFile) this.applySaved();
      }),
    );
    // Edits from any editor, and changes saved by other windows' Warp (the routing marker included)
    const watched = [this.file, this.keybindingsFile, this.routingAllowedFile].map((file) => path.basename(file));
    try {
      fs.mkdirSync(dir, { recursive: true });
      let timer;
      const watcher = fs.watch(dir, (_event, name) => {
        if (name && !watched.includes(name)) return;
        clearTimeout(timer);
        timer = setTimeout(() => this.apply(false), 100);
      });
      watcher.on('error', (error) => log.appendLine(`settings file watcher: ${error.message}`));
      context.subscriptions.push({
        dispose: () => {
          clearTimeout(timer);
          watcher.close();
        },
      });
    } catch (error) {
      log.appendLine(`can't watch the settings files: ${error.message}`);
    }
  }

  /**
   * Moves settings from the globalState mirror, where earlier versions kept them, into
   * settings.toml, once per machine. The mirror wins over an existing file, which earlier versions
   * only wrote for "Open settings file", so a file that differs is kept as settings.toml.bak. A
   * remote machine (SSH, WSL, containers) starts its files from the mirror the same way.
   */
  async migrate() {
    if (fs.existsSync(this.migratedFile)) return;
    const mirror = this.globalState.get(this.storageKey, {});
    fs.mkdirSync(path.dirname(this.file), { recursive: true });
    const replace = (file, text) => {
      const existing = read(file);
      if (existing && existing !== text) fs.copyFileSync(file, `${file}.bak`);
      fs.writeFileSync(file, text);
    };
    replace(this.file, renderToml(mirror));
    if (typeof mirror[KEYBINDINGS_KEY] === 'string') {
      replace(this.keybindingsFile, JSON.parse(mirror[KEYBINDINGS_KEY]));
    }
    // Routing off in the mirror was confirmed when it was turned off
    this.setRoutingOffAllowed(!isPrivateRouting(mirror));
    fs.writeFileSync(this.migratedFile, '');
    this.log.appendLine('moved settings into settings.toml');
  }

  /**
   * Reads both files into this window's entries (on top of `base` when given), and the changed
   * ones into the mirror; returns the changes (null for removed) and file errors. Private routing
   * only turns off once that's allowed on this machine: by Warp's settings page, which asks, or by
   * a sync with `confirm` set, which asks here. Until then it stays on. A file that can't be read or
   * parsed keeps its last entries while the other file still applies.
   */
  async sync(confirm, base) {
    // Until migrate() succeeds the file may be stale, and the mirror holds the settings
    if (!fs.existsSync(this.migratedFile)) {
      this.state = this.globalState.get(this.storageKey, {});
      return { changes: {}, errors: [] };
    }
    let errors;
    let settingsReadable;
    const fromFiles = () => {
      errors = [];
      settingsReadable = true;
      let next;
      try {
        next = applyToml(read(this.file), base ?? this.state);
      } catch (error) {
        settingsReadable = false;
        errors.push(`settings.toml: ${error.message}`);
        next = { ...this.state };
      }
      try {
        next = withKeybindings(next, read(this.keybindingsFile));
      } catch (error) {
        errors.push(`keybindings.yaml: ${error.message}`);
      }
      return next;
    };
    const unconfirmed = (entries) => !isPrivateRouting(entries) && !fs.existsSync(this.routingAllowedFile);
    let next = fromFiles();
    if (confirm && settingsReadable && unconfirmed(next)) {
      // One dialog for every sync that asks at once
      this.confirming ??= confirmPublicRouting().finally(() => {
        this.confirming = null;
      });
      if (await this.confirming) this.setRoutingOffAllowed(true);
      // The files and this window's entries may have changed while the dialog was open
      next = fromFiles();
    }
    if (settingsReadable && isPrivateRouting(next)) this.setRoutingOffAllowed(false);
    this.routingPending = settingsReadable && !confirm && unconfirmed(next);
    if (settingsReadable && unconfirmed(next)) {
      next = { ...next, HostAiPrivateRouting: encode(true) };
      if (confirm) {
        fs.writeFileSync(this.file, updateToml(read(this.file), { HostAiPrivateRouting: encode(true) }));
        vscode.window.showInformationMessage('Warp: private routing stays on.');
      }
    }
    const changes = changedEntries(this.state, next);
    this.state = next;
    for (const key of Object.keys(changes)) this.pendingChanges.add(key);
    if (Object.keys(changes).length) await this.updateMirror(changes);
    return { changes, errors };
  }

  /** Records whether private routing may be off on this machine. */
  setRoutingOffAllowed(allowed) {
    if (allowed) fs.writeFileSync(this.routingAllowedFile, '');
    else fs.rmSync(this.routingAllowedFile, { force: true });
  }

  /** Writes changed entries (null for removed) into the mirror every window shares. */
  async updateMirror(changes) {
    const mirror = { ...this.globalState.get(this.storageKey, {}) };
    for (const [key, value] of Object.entries(changes)) {
      if (value === null) delete mirror[key];
      else mirror[key] = value;
    }
    await this.globalState.update(this.storageKey, mirror);
  }

  /**
   * Reads the files into this window's entries; returns the entries for the page. The entries that
   * aren't settings come from the mirror, so the page also gets the ones other windows changed. If
   * a file can't be read, the entries keep their last values.
   */
  async load() {
    try {
      const { errors } = await this.sync(false, this.globalState.get(this.storageKey, {}));
      if (errors.length) vscode.window.showErrorMessage(`Warp couldn't read its settings: ${errors.join('; ')}`);
    } catch (error) {
      vscode.window.showErrorMessage(`Warp couldn't read its settings: ${error.message}`);
    }
    // The returned snapshot applies these entries when Warp starts
    this.pendingChanges.clear();
    return this.state;
  }

  /** Saves changed localStorage entries (null for removed) from the page. */
  async save(changes) {
    const next = { ...this.state };
    for (const [key, value] of Object.entries(changes)) {
      if (value === null) delete next[key];
      else next[key] = value;
      this.pendingChanges.delete(key);
    }
    this.state = next;
    // The files before the mirror's await, so a watcher sync in between can't read the old file
    // against the new entries
    if (fs.existsSync(this.migratedFile)) {
      try {
        // Warp's settings page asks before it turns private routing off. Allowing it is recorded
        // after the file, so another window that read the old file can't remove it (the watcher
        // picks it up). Turning routing on is recorded first, so a failed write can't leave off
        // allowed.
        const routingOn = 'HostAiPrivateRouting' in changes ? isPrivateRouting(next) : null;
        if (routingOn === true) this.setRoutingOffAllowed(false);
        // Keybindings first, so a syntax error in settings.toml can't hold them back
        if (changes[KEYBINDINGS_KEY] === null) {
          fs.writeFileSync(this.keybindingsFile, '');
        } else if (typeof changes[KEYBINDINGS_KEY] === 'string') {
          fs.writeFileSync(this.keybindingsFile, JSON.parse(changes[KEYBINDINGS_KEY]));
        }
        if (Object.keys(changes).some((key) => key in SETTINGS_MAP)) {
          fs.writeFileSync(this.file, updateToml(read(this.file), changes));
        }
        if (routingOn === false) this.setRoutingOffAllowed(true);
      } catch (error) {
        // E.g. a syntax error from an edit in progress. The file still wins the next time it's read.
        vscode.window.showErrorMessage(
          `Warp couldn't save your change, so it lasts until the settings file is read again: ${error.message}`,
        );
      }
    }
    await this.updateMirror(changes);
  }

  open() {
    return this.show(this.file, () => renderToml(this.state));
  }

  openKeybindings() {
    return this.show(this.keybindingsFile, () => KEYBINDINGS_HEADER);
  }

  async show(file, initialText) {
    if (!fs.existsSync(file)) {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, initialText());
    }
    const doc = await vscode.workspace.openTextDocument(file);
    await vscode.window.showTextDocument(doc, { preview: false });
  }

  /** A settings or keybindings file saved in a VS Code editor; the watcher may have synced it first. */
  async applySaved() {
    try {
      const result = await this.sync(true);
      if (result.errors.length) {
        vscode.window.showErrorMessage(`Warp couldn't apply the file: ${result.errors.join('; ')}`);
      }
    } catch (error) {
      vscode.window.showErrorMessage(`Warp couldn't apply the file: ${error.message}`);
      return;
    }
    this.log.appendLine('applied a saved settings file');
    if (this.notify() || !this.pendingChanges.size) return;
    const choice = await vscode.window.showInformationMessage(
      'Warp settings saved. Reload the Warp panel to apply them? This restarts its shell sessions.',
      'Reload now',
      'Later',
    );
    if (choice === 'Reload now') await this.onApplied();
  }

  /** Asks about turning private routing off when the files did that while nothing could ask (startup, another editor). */
  confirmRouting() {
    if (this.routingPending) this.apply(true);
  }

  /** A newer Warp save can finish while sync waits for the mirror; only send current values. */
  notify() {
    const current = {};
    for (const key of this.pendingChanges) current[key] = this.state[key] ?? null;
    if (!this.onChanged(current)) return false;
    this.pendingChanges.clear();
    return true;
  }

  /** Hands the running panel what changed in the files. */
  async apply(confirm) {
    try {
      const { errors } = await this.sync(confirm);
      for (const error of errors) this.log.appendLine(`settings files: ${error}`);
      if (this.pendingChanges.size) this.notify();
    } catch (error) {
      // E.g. a syntax error in an edit in progress; saving it in VS Code shows the error
      this.log.appendLine(`settings files: ${error.message}`);
    }
  }
}

module.exports = { SettingsFile, renderToml, applyToml, updateToml };
